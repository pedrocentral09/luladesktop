def remove_white_bg(img_path, out_path, white_thresh=240, flood_thresh=15):
    if not os.path.exists(img_path):
        print(f"Warning: {img_path} not found!")
        return None
    
    im = Image.open(img_path).convert('RGB')
    w, h = im.size
    pixels = im.load()

    # Binary mask of near-white pixels
    mask = Image.new('L', (w, h), 0)
    mask_pixels = mask.load()

    for y in range(h):
        for x in range(w):
            r, g, b = pixels[x, y]
            if r >= white_thresh and g >= white_thresh and b >= white_thresh:
                mask_pixels[x, y] = 255

    # Floodfill from boundaries to only remove background, preserving white shirts/eyes/teeth
    flood = mask.copy()
    for x in range(w):
        if flood.getpixel((x, 0)) == 255: ImageDraw.floodfill(flood, (x, 0), 128, thresh=flood_thresh)
        if flood.getpixel((x, h - 1)) == 255: ImageDraw.floodfill(flood, (x, h - 1), 128, thresh=flood_thresh)
    for y in range(h):
        if flood.getpixel((0, y)) == 255: ImageDraw.floodfill(flood, (0, y), 128, thresh=flood_thresh)
        if flood.getpixel((w - 1, y)) == 255: ImageDraw.floodfill(flood, (w - 1, y), 128, thresh=flood_thresh)

    # Invert to create alpha channel (0 where flood is 128, 255 elsewhere)
    alpha = Image.new('L', (w, h), 255)
    alpha_pixels = alpha.load()
    flood_pixels = flood.load()

    for y in range(h):
        for x in range(w):
            if flood_pixels[x, y] == 128:
                alpha_pixels[x, y] = 0

    rgba = im.convert('RGBA')
    rgba.putalpha(alpha)
    bbox = rgba.getbbox()
    if bbox:
        cropped = rgba.crop(bbox)
        cropped.save(out_path)
        print(f"Saved {out_path} with size {cropped.size}")
        return cropped
    else:
        rgba.save(out_path)
        return rgba

